/**
 * Generates the CSS the CLI and the docs app consume:
 *   css/theme.css            @theme mapping + foundation (no colour values)
 *   css/presets.css          every preset, switchable via <html data-preset>
 *   css/preset-<name>.css    one preset as the project's unscoped :root/.dark
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { PRESETS } from '../src/all-presets.ts';
import { presetToCss, presetsToSwitchableCss } from '../src/generate-css.ts';
import { themeCss } from '../src/theme-css.ts';

const out = new URL('../css/', import.meta.url);
mkdirSync(out, { recursive: true });

const foundation = readFileSync(new URL('../src/css/foundation.css', import.meta.url), 'utf8');
writeFileSync(new URL('theme.css', out), themeCss(foundation));
writeFileSync(new URL('presets.css', out), presetsToSwitchableCss(PRESETS));
for (const preset of PRESETS) {
  writeFileSync(
    new URL(`preset-${preset.name}.css`, out),
    `/* Generated by @sas-ui/tokens from the "${preset.name}" preset. */\n${presetToCss(preset, 'root')}`,
  );
}
console.log(`built ${PRESETS.length} presets → packages/tokens/css`);
