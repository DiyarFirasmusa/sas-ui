import { ALIAS_TOKENS, CORE_TOKEN_NAMES } from './token-names.ts';

/**
 * Tailwind v4 `@theme inline` mapping: every colour token becomes a utility
 * (`bg-surface`, `text-text-muted`, `border-stroke`) that reads the live CSS
 * variable, so switching preset or theme never needs a rebuild.
 */
export function themeColorBlock(): string {
  const names = [...CORE_TOKEN_NAMES, ...Object.keys(ALIAS_TOKENS)];
  const lines = names.map((name) => `  --color-${name}: var(--${name});`);
  return `@theme inline {\n${lines.join('\n')}\n}\n`;
}

export function themeCss(foundation: string): string {
  return `/* Generated by @sas-ui/tokens — do not edit by hand. */
@custom-variant dark (&:is(.dark *));

${themeColorBlock()}
${foundation}`;
}
