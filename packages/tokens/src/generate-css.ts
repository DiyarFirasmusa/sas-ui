import { ALIAS_TOKENS, CORE_TOKEN_NAMES } from './token-names.ts';
import type { Preset, ThemeTokens } from './token-names.ts';

export type PresetScope =
  /** Unscoped `:root` / `.dark` — the single preset of a project. */
  | 'root'
  /** `:root[data-preset="name"]` — one of several switchable presets. */
  | 'attribute';

function declarations(theme: ThemeTokens, indent: string): string {
  const lines = CORE_TOKEN_NAMES.map((name) => `${indent}--${name}: ${theme[name]};`);
  const aliases = Object.entries(ALIAS_TOKENS).map(
    ([alias, target]) => `${indent}--${alias}: var(--${target});`,
  );
  return [...lines, ...aliases].join('\n');
}

function selectors(preset: Preset, scope: PresetScope) {
  if (scope === 'root') {
    return { light: ':root', dark: ':root.dark, .dark' };
  }
  const attribute = `:root[data-preset="${preset.name}"]`;
  return { light: attribute, dark: `${attribute}.dark, .dark${attribute}` };
}

/** CSS custom properties for one preset: a light block and a dark block. */
export function presetToCss(preset: Preset, scope: PresetScope): string {
  const { light, dark } = selectors(preset, scope);
  return [
    `/* ${preset.name} — ${preset.label.en} · ${preset.description} */`,
    `${light} {`,
    '  color-scheme: light;',
    `  --radius: ${preset.radius};`,
    declarations(preset.light, '  '),
    '}',
    '',
    `${dark} {`,
    '  color-scheme: dark;',
    declarations(preset.dark, '  '),
    '}',
    '',
  ].join('\n');
}

/** Every preset, switchable at runtime through `<html data-preset="…">`. */
export function presetsToSwitchableCss(presets: readonly Preset[]): string {
  return [
    '/* Generated by @sas-ui/tokens — do not edit; edit the preset data. */',
    ...presets.map((preset) => presetToCss(preset, 'attribute')),
  ].join('\n');
}
